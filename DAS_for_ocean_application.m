    xcorr.channel_position_m, ...
	xcorr.offset_m, ...
	xcorr.time_lag, ...
	xcorr.time_interval, ...
	'subtitle', data.time_and_date, ...
	'use_hilbert',false);

if export_plot
	% export plot as png
	exportgraphics( ...
		correlogram, ...
		fullfile(dataset_name, ['correlogram_' dataset_name  '.png']));
end

% plot correlation statistics and export data to csv file
[correlation_statistics, xcorr_plot] = get_correlation_statistics( ...
	strain_filtered, ...
	data.sampling_frequency_Hz, ...
	data.distance_m, ...
	data.channel_distance_m, ...
	xcorr.channel_position_m, ...
	xcorr.offset_m, ...
	xcorr.time_lag, ...
	xcorr.time_interval, ...
	xcorr.filename_table, ...
	'subtitle', data.time_and_date, ...
	'offset_step', 2, ...
	'use_hilbert', false);

if export_plot
	% export plot as png
	exportgraphics( ...
		xcorr_plot, ...
		fullfile(dataset_name, ['cross_corr_stats_' dataset_name  '.png']));
end

% clear variables
clear xcorr correlogram correlation_statistics xcorr_plot
